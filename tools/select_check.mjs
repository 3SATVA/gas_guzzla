import { chromium } from 'playwright-core';
const BASE = process.env.BASE || 'http://localhost:4174/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const errs = [];
const page = async (vp, extra = {}) => { const c = await b.newContext({ viewport: vp, ...extra }); const p = await c.newPage(); p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text())); return p; };
const scenes = (p) => p.evaluate(() => __gg.game.scene.getScenes(true).map((s) => s.scene.key).join(','));
const sh = (p, n) => p.screenshot({ path: `shots/select_${n}.png` });
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);
let p = await page({ width: 1280, height: 720 });
await p.goto(BASE + '?fight=1'); await p.waitForTimeout(6000);
await sh(p, '01_fight_pick_fade'); log('pick', await scenes(p));
await p.keyboard.press('ArrowRight'); await p.waitForTimeout(600); await sh(p, '02_fight_pick_seek');
log('idx after right', await p.evaluate(() => __gg.select.index));
await p.keyboard.press('Enter'); await p.waitForTimeout(5000);
log('seek fight', await scenes(p), await p.evaluate(() => __gg.fight?.dbg().P.id)); await sh(p, '03_fight_seek');
await p.keyboard.press('Escape'); await p.waitForTimeout(1500);
log('back', await scenes(p), await p.evaluate(() => __gg.select.index));
await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(400); await p.keyboard.press('Enter'); await p.waitForTimeout(5000);
log('fade fight', await scenes(p), await p.evaluate(() => __gg.fight?.dbg().P.id)); await sh(p, '04_fight_fade');
await p.goto(BASE); await p.waitForTimeout(5000); await p.keyboard.press('Enter'); await p.waitForTimeout(1500);
log('drive sel', await scenes(p), await p.evaluate(() => __gg.select?.mode)); await sh(p, '05_drive_pick');
await p.keyboard.press('ArrowRight'); await p.waitForTimeout(500); await sh(p, '06_drive_pick_seek');
await p.keyboard.press('Enter'); await p.waitForTimeout(6000);
log('level', await scenes(p), await p.evaluate(() => __gg.game.registry.get('driver'))); await sh(p, '07_drive_level_seek');
await p.context().close();
p = await page({ width: 844, height: 390 }, { hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
await p.goto(BASE + '?fight=1'); await p.waitForTimeout(7000);
await sh(p, '08_phone_pick'); log('phone', await scenes(p));
const toScreen = (x, y) => p.evaluate(([x, y]) => { const s = __gg.select, c = s.cameras.main, r = __gg.game.canvas.getBoundingClientRect(), sc = r.width / __gg.game.scale.width; return [r.left + (x - c.scrollX) * sc, r.top + (y - c.scrollY) * sc]; }, [x, y]);
let [tx, ty] = await toScreen(952, 400); await p.touchscreen.tap(tx, ty); await p.waitForTimeout(500);
log('phone tap seek idx', await p.evaluate(() => [__gg.select.index, __gg.game.registry.get('lite')])); await sh(p, '09_phone_pick_seek');
[tx, ty] = await toScreen(640, 612); await p.touchscreen.tap(tx, ty); await p.waitForTimeout(6000);
log('phone GO', await scenes(p), await p.evaluate(() => __gg.fight?.dbg().P.id));
log('errs', errs);
await b.close();
